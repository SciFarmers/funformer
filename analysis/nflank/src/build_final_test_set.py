"""Per-track tables under the final convention: N-flank exclusion + 50-pos floor.

Writes an eval_results/test_set_final/ tree in the same shape as
eval_results/test_set/, so Table 1 and Figure 2 can be regenerated by pointing
TEST_SET_DIR at it. Tracks are kept only if they carry at least MIN_POS
positives ON THE KEPT INTERVALS -- counting them on the full set would admit
tracks whose positives all sit in the excluded N regions.
"""
import glob
import os
import sys

import numpy as np
import pandas as pd

ROOT = os.environ.get("REPO_ROOT") or os.path.dirname(os.path.dirname(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
HERE = os.path.join(ROOT, "analysis", "nflank")
OUT = os.path.join(ROOT, "eval_results", "test_set_final")
MIN_POS = 50


def main():
    os.makedirs(OUT, exist_ok=True)
    rows = []
    for f in sorted(glob.glob(os.path.join(HERE, "out", "*__*.csv"))):
        d = pd.read_csv(f)
        sp, model = d.species.iloc[0], d.model.iloc[0]
        # the sweep runs carry a run name as "model"; their exp name is that name
        exp = model if model.startswith("funformer_entex") else None
        if exp is None:
            sys.path.insert(0, os.path.join(ROOT, "analysis", "tss_strata", "src"))
            from manifest import checkpoint
            try:
                ck, _ = checkpoint(sp, model)
            except SystemExit:
                continue
            exp = ck.split("/")[1]
        keep = d.positives_kept >= MIN_POS
        sel = d[keep].copy()
        pt = pd.DataFrame({"track_idx": sel.track_idx,
                           "auroc": sel.auroc_kept, "auprc": sel.auprc_kept})
        pt.to_csv(os.path.join(OUT, f"{exp}_per_track.csv"), index=False)
        v = pt.dropna(subset=["auroc"])
        pd.DataFrame([{
            "exp_name": exp, "n_tracks_eval": len(v),
            "auroc_mean": v.auroc.mean(), "auroc_median": v.auroc.median(),
            "auroc_std": v.auroc.std(), "auprc_mean": v.auprc.mean(),
            "auprc_std": v.auprc.std()}]).to_csv(
            os.path.join(OUT, f"{exp}_summary.csv"), index=False)
        rows.append(dict(species=sp, model=model, exp=exp,
                         tracks_in=len(d), tracks_kept=len(v),
                         auroc=v.auroc.mean(), auprc=v.auprc.mean()))
    t = pd.DataFrame(rows)
    t.to_csv(os.path.join(HERE, "out", "final_test_set_summary.tsv"),
             sep="\t", index=False)
    print(f"wrote {len(rows)} per-track/summary pairs to {OUT}\n")
    print(t[~t.model.str.startswith("funformer_entex")]
          .sort_values(["species", "model"]).round(5).to_string(index=False))


if __name__ == "__main__":
    main()
